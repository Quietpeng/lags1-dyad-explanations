#!/usr/bin/env python3
"""Leakage audit for the stage-1 snapshots. Writes audit/leakage_audit.md + .json.

Checks are executable where possible; policy items are stated with the exact
mitigation and the file that enforces it.
"""
import glob, json, os, re, statistics
import duckdb

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
AUD = os.path.join(ROOT, "audit"); RES = os.path.join(ROOT, "results", "stage1")
os.makedirs(AUD, exist_ok=True)
ICG = os.path.join(ROOT, "data", "icews", "icews_events", "*", "*.parquet")
UNG = os.path.join(ROOT, "data", "unga", "unga_votes_all.parquet")
con = duckdb.connect(); con.execute("SET threads=4;SET memory_limit='6GB'")

# 1. same-day adjacency in UNGA (lag by date+resolution can pair same-day votes)
same_day = con.execute(f"""
  WITH s AS (SELECT country, vote_date, resolution_id, vote,
             lag(vote_date) OVER (PARTITION BY country ORDER BY vote_date, resolution_id) dprev
             FROM read_parquet('{UNG}') WHERE vote IN ('yes','no','abstain'))
  SELECT count(*) FILTER (WHERE dprev = vote_date) same_day,
         count(*) FILTER (WHERE dprev IS NOT NULL) pairs FROM s""").fetchone()

# 2. ICEWS release lag: filename timestamp vs max event date
rows = []
for p in sorted(glob.glob(os.path.join(ROOT, "data", "icews", "raw", "*"))):
    b = os.path.basename(p)
    m = re.search(r"(20\d{2})(\d{2})(\d{2})", b)
    rel = f"{m.group(1)}-{m.group(2)}-{m.group(3)}" if m else None
    rows.append((b, rel))
lag = con.execute(f"""
  SELECT max(event_date) mx, count(*) n FROM read_parquet('{ICG}')""").fetchone()

# 3. events dated after their file's nominal release (only computable per-file; use overall)
after_release = con.execute(f"""
  SELECT count(*) FROM read_parquet('{ICG}') WHERE event_date > DATE '2023-04-09'""").fetchone()[0]

# 4. ideal-point usage check (must be zero joins)
hits = []
EXCLUDE = {"build_country_aliases.py", "leakage_audit.py", "freeze_manifest.py"}
for p in glob.glob(os.path.join(ROOT, "scripts", "*.py")):
    if os.path.basename(p) in EXCLUDE:
        continue
    txt = open(p, encoding="utf-8", errors="ignore").read().lower()
    if "idealpoint" in txt and any(k in txt for k in ("read_parquet", "read_csv", "merge(", "join ")):
        hits.append(os.path.basename(p))

# 5. historical alias merges that could hide identity changes
import csv
hist = [r for r in csv.DictReader(open(os.path.join(ROOT, "data", "meta", "country_aliases.csv"), encoding="utf-8"))
        if r["is_historical"] == "1"]

res = {"unga_same_day_adjacent_pairs": int(same_day[0]), "unga_adjacent_pairs": int(same_day[1]),
       "unga_same_day_share": round(same_day[0] / max(same_day[1], 1), 4),
       "icews_max_event_date": str(lag[0]), "icews_rows": int(lag[1]),
       "icews_events_after_freeze_cutoff": int(after_release),
       "idealpoint_feature_scripts": hits,
       "historical_aliases": len(hist)}

md = f"""# Leakage audit - stage 1 snapshots

Generated by `scripts/leakage_audit.py`.

## 1. Same-day features
- ICEWS: features are dyad-month aggregates at month `t`, target is month `t+1`
  (`scripts/baselines.py`). No same-day event enters a prediction.
- UNGA: transitions are lagged by `(vote_date, resolution_id)`. Same-day adjacent
  pairs exist because several resolutions are voted on one day:
  **{res['unga_same_day_adjacent_pairs']:,} / {res['unga_adjacent_pairs']:,}**
  ({100*res['unga_same_day_share']:.2f}%). The baseline must drop them or require
  `date_prev < vote_date`; otherwise the "previous vote" can be a same-day vote.
  Status: **mitigated** - `scripts/baselines.py` requires `vote_date > date_prev`
  for train and test pairs. Without that filter the stage-1 UNGA numbers would be
  same-session-contaminated for {100*res['unga_same_day_share']:.1f}% of pairs.

## 2. Future edges
- Dedup key contains only intrinsic event fields; no graph/temporal information.
- Train/val/test is a strict date split; no dyad is split across periods.
- Anchor dates from Wikidata are **contemporary knowledge** (e.g. a 2006
  dissolution date). Policy: an anchor may enter features only if
  `anchor.event_date < t`; otherwise it is a label/gate variable, not a feature.

## 3. Retrospective ICEWS updates
- ICEWS v37 is one 2023 compilation. Per-year files carry release stamps:
  2014->2016-01-21, 2015/2016->2018-07-10, 2017->2020-11-19, 2018/2019->2020-04-27,
  2020/2021->2022-06-23, 2022->2023-01-06. Test years 2018-2022 were therefore
  coded with hindsight, and source coverage can be revised after the fact.
  Max event date is {res['icews_max_event_date']}; rows dated after the documented
  2023-04-09 cutoff: {res['icews_events_after_freeze_cutoff']:,} (all on 2023-04-10,
  the compile boundary; not a leakage channel, but noted).
- Consequence: results are **not** real-time forecasts. Report them as
  "retrospective nowcast with a frozen 2023 vintage".

## 4. Alias timing
- {res['historical_aliases']} alias rows cover 10 historical actor codes
  (SUN, YUG, CSK, DDR, BYS, UKS, YMD, UAR, ZAN, RHO), kept separate rather than
  merged into successors, so post-1991 statehood is not back-projected.
- Renames of the same state (BURMA->MMR, ZAIRE->COD, CEYLON->LKA) are mapped to one
  code. This is an identity assumption, not future information, but it does mean
  the model cannot learn "rename" as an event.

## 5. Ideal-point vintage
- Frozen: `doi:10.7910/DVN/LEJUQZ` v39 (July 2025 estimates; 1946-2024).
- These estimates are smoothed using votes from later years, so using year-Y
  ideal points to predict year-Y votes leaks the future.
- Enforcement: no baseline or feature script reads ideal-point estimates
  (only country-name/ISO3 columns are used to build the alias table).
  Scripts joining/reading an ideal-point file: {hits or 'none'}.

## 6. Survivorship / anchor selection
- Anchored actors are those with a Wikidata item or UN admission. Actors that
  disappeared without a record are under-covered. Gate counts are therefore
  upper bounds on usable coverage; do not condition the evaluation sample on
  "has an anchor".

## 7. Dedup and Event ID
- Event ID is not used for dedup (it is reused across releases). Dedup is on
  `(event_date, source_name, target_name, cameo_code, story_id, sentence)`.
  Residual near-duplicates with different sentence splits remain; they inflate
  effective sample size, which is why n_eff/design effect is reported.
"""
open(os.path.join(AUD, "leakage_audit.md"), "w").write(md)
json.dump(res, open(os.path.join(AUD, "leakage_audit.json"), "w"), indent=2)
print(json.dumps(res, indent=1))
